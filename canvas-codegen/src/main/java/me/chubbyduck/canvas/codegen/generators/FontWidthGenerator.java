package me.chubbyduck.canvas.codegen.generators;

import com.palantir.javapoet.AnnotationSpec;
import com.palantir.javapoet.CodeBlock;
import com.palantir.javapoet.JavaFile;
import com.palantir.javapoet.MethodSpec;
import com.palantir.javapoet.TypeSpec;
import java.io.IOException;
import java.net.http.HttpClient;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import javax.annotation.processing.Generated;
import javax.lang.model.element.Modifier;
import me.chubbyduck.canvas.codegen.Generator;
import me.chubbyduck.canvas.codegen.GeneratorConstants;
import me.chubbyduck.canvas.codegen.fonts.FontReader;

/**
 * Generates {@code <displayName>FontWidths}: the advance of every codepoint a vanilla font defines, read from MC Assets.
 * Each entry of {@code ranges()} is {@code start, end, advance, boldOffset}, where the bold offset is in half pixels.
 */
public record FontWidthGenerator(String displayName, String font, String version) implements Generator {

    private static final int RANGES_PER_CHUNK = 1024;

    @Override
    public void generateTo(final Path output) throws IOException {
        final FontReader reader = new FontReader(HttpClient.newHttpClient(), this.version);

        final Map<Integer, int[]> glyphs = new TreeMap<>();
        try {
            reader.readFont(this.font, glyphs);
        } catch (final InterruptedException exception) {
            Thread.currentThread().interrupt();
            throw new IOException("Interrupted reading font " + this.font, exception);
        }

        final List<int[]> ranges = this.mergeRanges(glyphs);

        final TypeSpec.Builder type = TypeSpec.classBuilder("%sFontWidths".formatted(this.displayName))
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addAnnotation(AnnotationSpec.builder(Generated.class).addMember("value", "$S", FontWidthGenerator.class.getName()).build())
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build());

        final CodeBlock.Builder copy = CodeBlock.builder()
            .addStatement("final int[] ranges = new int[$L]", ranges.size() * 4);
        int chunk = 0;
        for (int start = 0; start < ranges.size(); start += RANGES_PER_CHUNK) {
            final List<int[]> part = ranges.subList(start, Math.min(ranges.size(), start + RANGES_PER_CHUNK));
            final CodeBlock.Builder values = CodeBlock.builder().add("return new int[] {\n").indent();
            for (final int[] range : part) {
                values.add("0x$L, 0x$L, $L, $L,\n",
                    Integer.toHexString(range[0]), Integer.toHexString(range[1]), range[2], range[3]);
            }
            values.unindent().add("};\n");
            final String name = "chunk" + chunk++;
            type.addMethod(MethodSpec.methodBuilder(name)
                .addModifiers(Modifier.PRIVATE, Modifier.STATIC)
                .returns(int[].class)
                .addCode(values.build())
                .build());
            copy.addStatement("System.arraycopy($L(), 0, ranges, $L, $L)", name, start * 4, part.size() * 4);
        }
        type.addMethod(MethodSpec.methodBuilder("ranges")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .returns(int[].class)
            .addCode(copy.addStatement("return ranges").build())
            .build());

        JavaFile.builder(GeneratorConstants.makePackage("fonts"), type.build())
            .addFileComment("Generated by Canvas Code Generators (MC Version: $L). Do not edit.", reader.getResolvedVersion())
            .build()
            .writeTo(output);
    }

    private List<int[]> mergeRanges(final Map<Integer, int[]> glyphs) {
        final List<int[]> ranges = new ArrayList<>();
        int[] current = null;

        for (final Map.Entry<Integer, int[]> glyph : glyphs.entrySet()) {
            final int codepoint = glyph.getKey();
            final int[] metrics = glyph.getValue();

            if (current != null
                && current[1] + 1 == codepoint
                && current[2] == metrics[0]
                && current[3] == metrics[1]) {
                current[1] = codepoint;
                continue;
            }

            current = new int[]{codepoint, codepoint, metrics[0], metrics[1]};
            ranges.add(current);
        }

        return ranges;
    }

}
