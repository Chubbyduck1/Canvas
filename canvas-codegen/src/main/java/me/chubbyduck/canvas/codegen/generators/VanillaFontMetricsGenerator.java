package me.chubbyduck.canvas.codegen.generators;

import com.palantir.javapoet.AnnotationSpec;
import com.palantir.javapoet.ClassName;
import com.palantir.javapoet.CodeBlock;
import com.palantir.javapoet.FieldSpec;
import com.palantir.javapoet.JavaFile;
import com.palantir.javapoet.MethodSpec;
import com.palantir.javapoet.TypeSpec;
import java.io.IOException;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;
import javax.annotation.processing.Generated;
import javax.lang.model.element.Modifier;
import me.chubbyduck.canvas.codegen.Generator;
import me.chubbyduck.canvas.codegen.GeneratorConstants;

/**
 * Generates {@code VanillaFontMetrics}: looks a codepoint up in the {@code <displayName>FontWidths} table of each given font.
 */
public class VanillaFontMetricsGenerator implements Generator {

    private static final ClassName KEY = ClassName.get("net.kyori.adventure.key", "Key");

    private final List<FontWidthGenerator> fonts;

    public VanillaFontMetricsGenerator(final List<FontWidthGenerator> fonts) {
        this.fonts = List.copyOf(fonts);
    }

    @Override
    public void generateTo(final Path output) throws IOException {
        final String fontsPackage = GeneratorConstants.makePackage("fonts");
        final TypeSpec.Builder type = TypeSpec.classBuilder("VanillaFontMetrics")
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addAnnotation(AnnotationSpec.builder(Generated.class).addMember("value", "$S", VanillaFontMetricsGenerator.class.getName()).build())
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build());

        final CodeBlock.Builder select = CodeBlock.builder().addStatement("final int[] ranges");
        for (int i = 0; i < this.fonts.size(); i++) {
            final FontWidthGenerator font = this.fonts.get(i);
            final String field = font.displayName().toUpperCase(Locale.ROOT);
            type.addField(FieldSpec.builder(int[].class, field, Modifier.PRIVATE, Modifier.STATIC, Modifier.FINAL)
                .initializer("$T.ranges()", ClassName.get(fontsPackage, font.displayName() + "FontWidths"))
                .build());

            final String key = font.font().contains(":") ? font.font() : "minecraft:" + font.font();
            if (i == 0) {
                select.beginControlFlow("if (font.asString().equals($S))", key);
            } else {
                select.nextControlFlow("else if (font.asString().equals($S))", key);
            }
            select.addStatement("ranges = $N", field);
        }
        select.nextControlFlow("else")
            .addStatement("return -1")
            .endControlFlow();

        final CodeBlock search = CodeBlock.builder()
            .addStatement("int low = 0")
            .addStatement("int high = ranges.length / 4 - 1")
            .beginControlFlow("while (low <= high)")
            .addStatement("final int mid = (low + high) >>> 1")
            .addStatement("final int offset = mid * 4")
            .beginControlFlow("if (codepoint < ranges[offset])")
            .addStatement("high = mid - 1")
            .nextControlFlow("else if (codepoint > ranges[offset + 1])")
            .addStatement("low = mid + 1")
            .nextControlFlow("else")
            .addStatement("return ranges[offset + field]")
            .endControlFlow()
            .endControlFlow()
            .addStatement("return -1")
            .build();

        type.addMethod(MethodSpec.methodBuilder("value")
            .addJavadoc("Field {@code field} ({@code 2} = advance, {@code 3} = bold offset in half pixels) of the range holding\n")
            .addJavadoc("{@code codepoint} in {@code font}, or {@code -1} if the font or codepoint is unknown.\n")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .returns(int.class)
            .addParameter(KEY, "font", Modifier.FINAL)
            .addParameter(int.class, "codepoint", Modifier.FINAL)
            .addParameter(int.class, "field", Modifier.FINAL)
            .addCode(select.build())
            .addCode(search)
            .build());

        JavaFile.builder(fontsPackage, type.build())
            .addFileComment("Generated by Canvas Code Generators. Do not edit.")
            .build()
            .writeTo(output);
    }

}
