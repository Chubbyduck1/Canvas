package me.chubbyduck.canvas.codegen.generators;

import com.palantir.javapoet.AnnotationSpec;
import com.palantir.javapoet.CodeBlock;
import com.palantir.javapoet.JavaFile;
import com.palantir.javapoet.MethodSpec;
import com.palantir.javapoet.TypeSpec;
import java.io.IOException;
import java.net.http.HttpClient;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import javax.annotation.processing.Generated;
import javax.lang.model.element.Modifier;
import me.chubbyduck.canvas.codegen.Generator;
import me.chubbyduck.canvas.codegen.GeneratorConstants;
import me.chubbyduck.canvas.codegen.unicode.ArabicShapingFile;
import me.chubbyduck.canvas.codegen.unicode.UcdReader;
import me.chubbyduck.canvas.codegen.unicode.UnicodeDataFile;
import org.jspecify.annotations.NonNull;

/**
 * Generates {@code ArabicShapingData}: joining types and presentation forms from the Unicode Character Database, for
 * shaping Arabic-script text into the forms the client draws.
 */
public record ArabicShapingGenerator(@NonNull String version) implements Generator {

    private static final int LAM = 0x0644;

    /**
     * Arabic Presentation Forms-B, which holds the lam-alef ligatures; Forms-A ligatures are optional and not used.
     */
    private static final int FORMS_B = 0xFE70;
    private static final List<String> FORM_TAGS = List.of("isolated", "final", "initial", "medial");

    @Override
    public void generateTo(final Path output) throws IOException {
        final UcdReader reader = new UcdReader(HttpClient.newHttpClient(), this.version);
        final ArabicShapingFile shaping;
        final UnicodeDataFile data;
        try {
            shaping = reader.arabicShaping();
            data = reader.unicodeData();
        } catch (final InterruptedException exception) {
            Thread.currentThread().interrupt();
            throw new IOException("Interrupted reading the Unicode Character Database", exception);
        }

        final TypeSpec type = TypeSpec.classBuilder("ArabicShapingData")
            .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
            .addAnnotation(AnnotationSpec.builder(Generated.class).addMember("value", "$S", ArabicShapingGenerator.class.getName()).build())
            .addMethod(MethodSpec.constructorBuilder().addModifiers(Modifier.PRIVATE).build())
            .addMethod(this.table(
                "joiningTypes",
                "Sorted {@code start, end, joiningType} ranges; codepoints not listed are non-joining ({@code 'U'}).",
                this.joiningTypes(shaping, data)))
            .addMethod(this.table(
                "forms",
                "Sorted {@code base, isolated, final, initial, medial} entries; {@code 0} where a form doesn't exist.",
                this.forms(data)))
            .addMethod(this.table(
                "lamAlef",
                "Sorted {@code alef, isolated, final} entries: the ligature lam followed by that alef becomes.",
                this.lamAlef(data)))
            .build();

        JavaFile.builder(GeneratorConstants.makePackage("text"), type)
            .addFileComment("Generated by Canvas Code Generators (Unicode Version: $L). Do not edit.", shaping.version())
            .build()
            .writeTo(output);
    }

    /**
     * Explicit joining types from {@code ArabicShaping.txt}; unlisted marks and format characters are transparent
     * ({@code 'T'}). Non-joining codepoints are left out.
     */
    @NonNull
    private List<int[]> joiningTypes(final @NonNull ArabicShapingFile shaping, final @NonNull UnicodeDataFile data) {
        final Map<Integer, Character> types = new TreeMap<>(shaping.joiningTypes());
        for (final UnicodeDataFile.Entry entry : data.characters()) {
            if (entry.isTransparent()) {
                types.putIfAbsent(entry.codepoint(), 'T');
            }
        }

        final List<int[]> ranges = new ArrayList<>();
        int[] current = null;
        for (final Map.Entry<Integer, Character> type : types.entrySet()) {
            final int codepoint = type.getKey();
            final char joining = type.getValue();
            if (joining == 'U') {
                continue;
            }
            if (current != null && current[1] + 1 == codepoint && current[2] == joining) {
                current[1] = codepoint;
                continue;
            }
            current = new int[]{codepoint, codepoint, joining};
            ranges.add(current);
        }
        return ranges;
    }

    /**
     * Single-letter {@code <isolated>}, {@code <final>}, {@code <initial>} and {@code <medial>} decompositions. Later
     * (higher) codepoints win, so the basic Arabic Presentation Forms-B block beats Forms-A.
     */
    @NonNull
    private List<int[]> forms(final @NonNull UnicodeDataFile data) {
        final Map<Integer, int[]> forms = new TreeMap<>();
        for (final UnicodeDataFile.Entry entry : data.characters()) {
            final int form = this.form(entry);
            if (form < 0 || entry.decomposition().length != 1) {
                continue;
            }
            forms.computeIfAbsent(entry.decomposition()[0], base -> new int[]{base, 0, 0, 0, 0})[form + 1] = entry.codepoint();
        }
        return List.copyOf(forms.values());
    }

    /**
     * Two-letter {@code <isolated>} and {@code <final>} decompositions starting with lam, in Presentation Forms-B.
     */
    @NonNull
    private List<int[]> lamAlef(final @NonNull UnicodeDataFile data) {
        final Map<Integer, int[]> ligatures = new TreeMap<>();
        for (final UnicodeDataFile.Entry entry : data.characters()) {
            final int form = this.form(entry);
            if (form < 0 || form > 1 || entry.decomposition().length != 2 || entry.decomposition()[0] != LAM
                || entry.codepoint() < FORMS_B) {
                continue;
            }
            ligatures.computeIfAbsent(entry.decomposition()[1], alef -> new int[]{alef, 0, 0})[form + 1] = entry.codepoint();
        }
        return List.copyOf(ligatures.values());
    }

    /**
     * Index of the entry's positional form in {@link #FORM_TAGS}, or -1 if it isn't one.
     */
    private int form(final UnicodeDataFile.@NonNull Entry entry) {
        final String tag = entry.decompositionTag();
        return tag == null ? -1 : FORM_TAGS.indexOf(tag);
    }

    /**
     * {@code static int[] name()} returning the rows flattened, one row per line.
     */
    @NonNull
    private MethodSpec table(final @NonNull String name, final @NonNull String javadoc, final @NonNull List<int[]> rows) {
        final CodeBlock.Builder values = CodeBlock.builder().add("return new int[] {\n").indent();
        for (final int[] row : rows) {
            final List<String> cells = new ArrayList<>(row.length);
            for (final int value : row) {
                cells.add(name.equals("joiningTypes") && cells.size() == 2 ? "'" + (char) value + "'" : "0x" + Integer.toHexString(value));
            }
            values.add("$L,\n", String.join(", ", cells));
        }
        values.unindent().add("};\n");

        return MethodSpec.methodBuilder(name)
            .addJavadoc(javadoc + "\n")
            .addModifiers(Modifier.PUBLIC, Modifier.STATIC)
            .returns(int[].class)
            .addCode(values.build())
            .build();
    }

}
